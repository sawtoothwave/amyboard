# AMYboard Sketch
# DESCRIPTION: Custom drum kit: the 11 sounds of a Korg Mini Pops sample kit stored as user patch 1024, loaded on MIDI channel 11 like a stock kit, playing a demo beat.
# Top-level code runs once at boot. loop(step) is called every 32nd note.
#
# HOW TO MAKE YOUR OWN DRUM KIT AS A CUSTOM PATCH, in four steps:
#
#  1. Load each drum sample into an AMY "memory PCM" preset (any preset number
#     >= 1000 is safely clear of the baked-in sample banks). Here the samples
#     ship inside this sketch as zlib-compressed base64 strings (22.05kHz mono
#     16-bit, same rate as the built-in Gamma9001 kits) so the sketch is
#     self-contained and shareable on AMYboard World.
#
#     If your samples are WAV files on the SD card instead, skip the embedded
#     strings and load them straight from disk:
#         amy.load_sample('/sd/mykit/kick.wav', preset=1000)   # copy into RAM
#     or stream from the card without using sample RAM:
#         amy.disk_sample('/sd/mykit/kick.wav', preset=1000)
#
#     To make embedded strings like the ones below from your own WAVs, on your
#     computer (16-bit mono WAVs; pass the file's rate as sr= when loading):
#         import wave, zlib, base64
#         w = wave.open('kick.wav'); pcm = w.readframes(w.getnframes())
#         txt = base64.b64encode(zlib.compress(pcm, 9)).decode()
#
#  2. Store the kit's oscillator bank as a USER PATCH: a single voice with one
#     PCM osc per drum, written with a patch_string. The built-in patch table
#     ends at 390 (the last Gamma9001 drum kit); user patches live at
#     1024 and up (32 slots), so our kit becomes patch 1024.
#
#  3. Load that patch on a synth exactly like you'd load a stock kit
#     (amy.send(synth=11, num_voices=1, patch=384, synth_flags=3) is the
#     TR-808) -- just say patch=1024 instead. We use synth 11, so the kit
#     answers to a MIDI keyboard or sequencer on channel 11, next to the stock
#     drum channel 10.
#
#  4. Give MIDI channel 11 a note map: one midi_note_cmd per drum routes a GM
#     note number to its osc, with the per-drum gain in the map's velocity
#     scale (5.0 = unity). The stock kits carry these maps inside their ROM
#     patch strings; a memory patch stores osc settings only, so we attach the
#     maps to the channel ourselves after loading the patch.
#
# loop() then plays a normal drum pattern through the patch. Delete it and
# keep steps 1-4 if you just want the kit.

