def loop(step):
    s = step % 32
    bar = (step // 32) % 4
    if s in kick_steps:
        amy.send(synth=SYNTH, note=KICK, vel=1)
    if s in snare_steps:
        amy.send(synth=SYNTH, note=SNARE if bar < 3 else SNARE_BRIGHT, vel=0.8)
    if s in ohat_steps:
        amy.send(synth=SYNTH, note=OHAT, vel=0.35)
    elif s in hat_steps:
        amy.send(synth=SYNTH, note=CHAT, vel=0.5 if s % 8 == 0 else 0.3)
    if s in rim_steps:
        amy.send(synth=SYNTH, note=RIM, vel=0.5)
    if bar == 3 and s >= 24 and s % 2 == 0:      # bongo fill into bar 1
        amy.send(synth=SYNTH, note=BONGO_LO if s < 28 else BONGO_HI, vel=0.7)
    if bar == 0 and s == 4:
        amy.send(synth=SYNTH, note=BOOM, vel=0.6)

